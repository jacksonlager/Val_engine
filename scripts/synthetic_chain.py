def write_workbook(slug: str) -> Path:
    prev = {"2026Q4": "2026Q3", "2027Q1": "2026Q4", "2027Q2": "2027Q1"}[slug]
    src_dir = CHAIN / "build" / prev
    src = src_dir / f"portfolio_{LABEL[slug].replace(' ', '_')}.xlsx"
    if not src.exists():
        raise SystemExit(f"{src} missing: run the previous quarter's `decide` first")
    out = workbook_path(slug)
    out.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy(src_dir / "open_items_carry.yaml", out.parent / "open_items_carry.yaml")
    book = _book(src)
    wb = openpyxl.load_workbook(src)
    ws = wb["Portfolio"]
    fn, edits = EVENTS[slug]
    edit_rows = []
    for company, column, value, why in edits:
        r = _row_of(ws, company)
        c = _find(ws, column)
        was = ws.cell(row=r, column=c).value
        ws.cell(row=r, column=c).value = value
        edit_rows.append([company, column, was, value, why])
    act = wb[f"{LABEL[slug]} Activity"]
    _write_activity(act, fn(book))
    _add_marker(wb, edit_rows)
    wb.save(out)
    ensure_policy(slug)
    write_malformed(slug, out)
    print(f"wrote {out} ({len(fn(book))} events, {len(edits)} metric edits)")
    return out


# ----------------------------------------------------------------------------- malformed variants

def write_malformed(slug: str, clean: Path) -> None:
    """Deliberately broken copies of the clean workbook, each with one defect, under malformed/<slug>/.
    Never part of the chain; each must be refused or blocked by ingest."""
    mdir = CHAIN / "malformed" / slug
    if mdir.exists():
        shutil.rmtree(mdir)
    mdir.mkdir(parents=True)
    label = LABEL[slug]
    act_name = f"{label} Activity"
    year = label.split()[1]

    def variant(name: str, mutate) -> None:
        wb = openpyxl.load_workbook(clean)
        mutate(wb)
        wb.save(mdir / f"SYNTHETIC_MALFORMED_{name}_{label.replace(' ', '_')}.xlsx")

    def first_priced_round_row(ws) -> int:
        ev = _find(ws, "Event")
        for r in range(2, ws.max_row + 1):
            if ws.cell(row=r, column=ev).value == "Priced Equity Round":
                return r
        raise KeyError("no priced round")

    variant("missing_post_money", lambda wb: wb[act_name].cell(row=first_priced_round_row(wb[act_name]),
                                                               column=_find(wb[act_name], "Post-Money / Deal Value ($M)")).__setattr__("value", None))
    variant("unreadable_cell", lambda wb: wb[act_name].cell(row=first_priced_round_row(wb[act_name]),
                                                            column=_find(wb[act_name], "HC Ownership After (FD %)")).__setattr__("value", "TBD"))

    def duplicate_row(wb):
        ws = wb["Portfolio"]
        ws.append([c.value for c in ws[2]])
    variant("duplicate_portfolio_row", duplicate_row)

    def unknown_event(wb):
        ws = wb[act_name]
        ws.append([datetime(int(year), {"Q1": 2, "Q2": 5, "Q3": 8, "Q4": 11}[label.split()[0]], 3), ws.cell(row=2, column=2).value,
                   "SPAC Merger", "Merged into a listed SPAC", 500.0, None, 0.02, None, "Structure not in the schema."])
    variant("unknown_event_type", unknown_event)

    def out_of_window(wb):
        ws = wb[act_name]
        r = first_priced_round_row(ws)
        ws.cell(row=r, column=_find(ws, "Date")).value = datetime(int(year) + 1, 1, 15)
    variant("event_after_measurement_date", out_of_window)

    def conflicting_rows(wb):
        ws = wb[act_name]
        ev = _find(ws, "Event")
        for r in range(2, ws.max_row + 1):
            if ws.cell(row=r, column=ev).value in ("Shutdown", "Acquisition (Closed)"):
                company = ws.cell(row=r, column=_find(ws, "Company")).value
                d = ws.cell(row=r, column=_find(ws, "Date")).value
                ws.append([d.replace(day=min(28, d.day + 7)), company, "Priced Equity Round", "Series Z", 99.0, None, 0.05, None,
                           "A financing dated after the exit — cannot both be true."])
                return
        raise KeyError("no terminal event to contradict")
    variant("financing_after_exit", conflicting_rows)

    def prior_mark_off(wb):
        ws = wb["Portfolio"]
        c = _find(ws, "Prior Mark ($M)")
        ws.cell(row=3, column=c).value = float(ws.cell(row=3, column=c).value or 0) + 1.0
    variant("prior_mark_unreconciled", prior_mark_off)

    def euro_cell(wb):
        ws = wb[act_name]
        r = first_priced_round_row(ws)
        ws.cell(row=r, column=_find(ws, "Post-Money / Deal Value ($M)")).value = "€120.0M"
    variant("non_usd_currency", euro_cell)

    def wrong_quarter_sheet(wb):
        wb[act_name].title = f"Q{int(label.split()[0][1]) % 4 + 1} {year} Activity"
    variant("activity_sheet_wrong_quarter", wrong_quarter_sheet)

    def duplicate_activity(wb):
        ws = wb[act_name]
        ws.append([c.value for c in ws[2]])
    variant("duplicate_activity_row", duplicate_activity)


# ----------------------------------------------------------------------------- compare

def compare(slug: str) -> int:
    """Run the quarter and diff against expectations/<slug>.yaml. Exit code = number of mismatches."""
    exp_path = CHAIN / "expectations" / f"{slug}.yaml"
    exp = yaml.safe_load(exp_path.read_text())
    r, paths, provider = run_quarter(slug)
    run = r.run
    by = run.by_company()
    mismatches: list[str] = []
    superseded = 0
    for company, e in (exp.get("companies") or {}).items():
        c = by.get(company)
        if c is None:
            mismatches.append(f"{company}: not in run")
            continue
        if e.get("superseded"):
            # An expectation shown to be a derivation error, kept verbatim with its `resolution:` so
            # the record of what was expected first survives; it is reported, not compared.
            superseded += 1
            print(f"  superseded {company}: {e.get('resolution', '').strip()[:160]}")
            continue
        if "proposed_mark" in e and abs(float(e["proposed_mark"]) - c.proposed_mark) > float(e.get("tolerance", 0.01)):
            mismatches.append(f"{company}: proposed {c.proposed_mark:.4f} != expected {float(e['proposed_mark']):.4f}")
        if "readiness" in e and c.readiness.value != e["readiness"]:
            mismatches.append(f"{company}: readiness {c.readiness.value} != expected {e['readiness']}")
        if "disposition" in e and c.disposition.value != e["disposition"]:
            mismatches.append(f"{company}: disposition {c.disposition.value} != expected {e['disposition']}")
        if "realized_quarter" in e and abs(float(e["realized_quarter"]) - c.realized_quarter) > 0.01:
            mismatches.append(f"{company}: realized {c.realized_quarter:.4f} != expected {float(e['realized_quarter']):.4f}")
        got = {f.rule_id for f in c.flags}
        for rid in e.get("flags_include", []) or []:
            if rid not in got:
                mismatches.append(f"{company}: expected flag {rid} missing (has {sorted(got)})")
        for rid in e.get("flags_exclude", []) or []:
            if rid in got:
                mismatches.append(f"{company}: flag {rid} fired but was not expected (has {sorted(got)})")
        if "status_after" in e and c.status_after.value != e["status_after"]:
            mismatches.append(f"{company}: status {c.status_after.value} != expected {e['status_after']}")
    t = exp.get("totals") or {}
    if "readiness" in t and dict(run.totals.readiness) != t["readiness"]:
        mismatches.append(f"totals.readiness {dict(run.totals.readiness)} != expected {t['readiness']}")
    if "positions" in t and run.totals.positions != t["positions"]:
        mismatches.append(f"totals.positions {run.totals.positions} != expected {t['positions']}")
    blocking = [v for v in run.validation if v.blocking]
    if exp.get("blocking_validation", 0) != len(blocking):
        mismatches.append(f"blocking validation issues {len(blocking)} != expected {exp.get('blocking_validation', 0)}: "
                          + "; ".join(f"{v.rule_id} {v.company}" for v in blocking[:8]))
    print(f"{slug}: run {run.manifest.run_id} provider {provider} readiness {dict(run.totals.readiness)} "
          f"prior {run.totals.prior_nav:,.1f} proposed {run.totals.proposed_nav:,.1f} booked {run.totals.booked_nav:,.1f}")
    for m in mismatches:
        print("  MISMATCH", m)
    print(f"{len(mismatches)} mismatch(es) against {exp_path.relative_to(ROOT)}"
          + (f"; {superseded} expectation(s) superseded by a documented derivation error" if superseded else ""))
    return len(mismatches)


# ----------------------------------------------------------------------------- main

def main(argv: list[str]) -> int:
    if not argv:
        print(__doc__)
        return 2
    stage = argv[0]
    slug = argv[1] if len(argv) > 1 else "2026Q3"
    LEDGER.mkdir(parents=True, exist_ok=True)
    if stage == "q3":
        decide("2026Q3")
        publish_and_build("2026Q3")
    elif stage == "workbook":
        write_workbook(slug)
    elif stage == "run":
        return compare(slug)
    elif stage == "decide":
        decide(slug)
        publish_and_build(slug)
    elif stage == "reset":
        for p in (LEDGER, CHAIN / "build"):
            if p.exists():
                shutil.rmtree(p)
        print("chain ledger and builds removed; workbooks and expectations kept")
    else:
        print(__doc__)
        return 2
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
