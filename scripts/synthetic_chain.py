# ----------------------------------------------------------------------------- helpers

def quarter_dir(slug: str) -> Path:
    return CHAIN / slug


def workbook_path(slug: str) -> Path:
    return quarter_dir(slug) / f"SYNTHETIC_portfolio_{LABEL[slug].replace(' ', '_')}.xlsx"


def policy_path(slug: str) -> Path:
    return ROOT / "rules" / f"{slug}.yaml"


def ensure_policy(slug: str) -> Path:
    p = policy_path(slug)
    if not p.exists():
        prev = {"2026Q4": "2026Q3", "2027Q1": "2026Q4", "2027Q2": "2027Q1"}[slug]
        write_next_policy(policy_path(prev), note="synthetic test chain: inherits everything, window only")
    return p


def paths_for(slug: str) -> RunPaths:
    wb = REAL_WORKBOOK if slug == "2026Q3" else workbook_path(slug)
    return RunPaths.default(root=ROOT, workbook=wb, policy=ensure_policy(slug), ledger_dir=LEDGER)


def run_quarter(slug: str, *, adjudicate: bool = False):
    paths = paths_for(slug)
    provider = provider_for(ROOT, paths.policy)
    return execute(paths, provider=provider, adjudicate=adjudicate, generated_at=GENERATED_AT[slug]), paths, provider


def _add_marker(wb: openpyxl.Workbook, edits: list[list[Any]] | None = None) -> None:
    if SYNTHETIC_SHEET not in wb.sheetnames:
        ws = wb.create_sheet(SYNTHETIC_SHEET, 0)
        for row in MARKER_TEXT:
            ws.append(row)
        ws.column_dimensions["A"].width = 120
    if edits:
        ws2 = wb.create_sheet("Synthetic Edits")
        ws2.append(["Company", "Column", "Was", "Now", "Why (the case this edit builds)"])
        for row in edits:
            ws2.append(row)
        for col, w in zip("ABCDE", (22, 20, 12, 12, 90)):
            ws2.column_dimensions[col].width = w


def _find(ws, header: str) -> int:
    for j, cell in enumerate(ws[1], start=1):
        if cell.value == header:
            return j
    raise KeyError(header)


def _row_of(ws, company: str) -> int:
    col = _find(ws, "Company")
    for r in range(2, ws.max_row + 1):
        if ws.cell(row=r, column=col).value == company:
            return r
    raise KeyError(company)


def _write_activity(ws, rows: list[dict[str, Any]]) -> None:
    cols = list(ACTIVITY_COLUMNS)
    for r in rows:
        ws.append([r.get(c) for c in cols])


def _book(slug_prev_build: Path) -> dict[str, Any]:
    """The emitted Portfolio tab as a dict of company -> column -> value (the opening book)."""
    wb = openpyxl.load_workbook(slug_prev_build, data_only=False)
    ws = wb["Portfolio"]
    headers = [c.value for c in ws[1]]
    out = {}
    for row in ws.iter_rows(min_row=2, values_only=True):
        d = dict(zip(headers, row))
        if d.get("Company"):
            out[d["Company"]] = d
    return out


