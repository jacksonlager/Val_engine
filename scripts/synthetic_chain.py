def decide(slug: str) -> list[dict[str, Any]]:
    """Record one decision per not-Ready position into the chain ledger. Returns the records."""
    r, paths, provider = run_quarter(slug)
    run = r.run
    cfg = r.config
    quarter = cfg.quarter.label
    created = (GENERATED_AT[slug].date()).isoformat()
    records: list[dict[str, Any]] = []
    named = DECISIONS.get(slug, {})
    for c in run.companies:
        if c.readiness is Readiness.READY:
            continue
        addressed = set(c.override.rule_ids_addressed) if c.override else set()
        open_ids = sorted({f.rule_id for f in c.flags if f.severity in (Severity.BLOCK, Severity.REVIEW)} - addressed)
        spec = named.get(c.company)
        rec: dict[str, Any] = {"company": c.company, "quarter": quarter, "proposed": float(c.proposed_mark),
                               "approver": REVIEWER, "created_at": created}
        if spec and "closing_cap" in spec:
            cap = float(spec["closing_cap"])
            rule = next((f.rule_id for f in c.flags if f.rule_id in ("X-113", "X-101")), open_ids[0] if open_ids else "X-113")
            rec.update(booked=round(c.ownership_after * cap, 6), reason=spec["reason"],
                       rule_ids_addressed=sorted(set(open_ids) | {rule}), source_suggestion=f"{rule}/price",
                       evidence={"kind": "closing_price", "as_of": cfg.quarter.measurement_date.isoformat(),
                                 "market_cap_musd": cap, "source": "SYNTHETIC test decision (invented)",
                                 "ownership": c.ownership_after})
        elif spec and "suggestion" in spec:
            rid, key = spec["suggestion"]
            flag = next(f for f in c.flags if f.rule_id == rid)
            sug = next((s for s in flag.suggestions if s.key == key), None)
            if sug is None:   # the alternative was not produced this quarter (e.g. no live history): fall back, and say so
                rec.update(booked=float(c.proposed_mark), reason=spec["reason"] + " [alternative not available; booked as proposed]",
                           rule_ids_addressed=open_ids, source_suggestion=f"{rid}/as_proposed")
            else:
                rec.update(booked=float(sug.booked), reason=spec["reason"], rule_ids_addressed=open_ids,
                           source_suggestion=f"{rid}/{key}")
        else:
            pr = c.recommendation
            if pr is not None:
                rec.update(booked=float(pr.booked), reason=f"Policy recommendation ({pr.rule_id}/{pr.key}): {pr.label}",
                           rule_ids_addressed=open_ids, source_suggestion=f"{pr.rule_id}/{pr.key}")
            else:
                rec.update(booked=float(c.proposed_mark), reason="Accepted as proposed (no actionable recommendation).",
                           rule_ids_addressed=open_ids)
        append_override(paths.overrides, rec)
        records.append(rec)
    # the log a reader can audit without opening the yaml
    lines = [f"# Simulated reviewer decisions — {quarter} (synthetic chain)", "",
             f"Run `{run.manifest.run_id}` on `{paths.workbook.name}`, provider `{provider}`. One decision per position that was "
             "not Ready; every one recorded under the reviewer's name in `ledger/overrides.yaml`.", "",
             "| Company | Readiness | Proposed | Booked | Rules addressed | Reason |", "|---|---|---:|---:|---|---|"]
    by = run.by_company()
    for rec in records:
        c = by[rec["company"]]
        lines.append(f"| {rec['company']} | {c.readiness.value} | {rec['proposed']:.3f} | {rec['booked']:.3f} | "
                     f"{', '.join(rec['rule_ids_addressed'])} | {rec['reason']} |")
    (LEDGER / f"decisions_{slug}.md").write_text("\n".join(lines) + "\n")
    return records


def publish_and_build(slug: str) -> Path:
    """Publish the decided book under the second name and emit next quarter's input with `build`."""
    r, paths, provider = run_quarter(slug)
    waiting = [c.company for c in r.run.companies if c.readiness is not Readiness.READY]
    if waiting:
        raise SystemExit(f"{slug}: {len(waiting)} position(s) still not Ready after decisions: {waiting}")
    rec = publish_run(r.run, ROOT, approver=PUBLISHER, note=f"SYNTHETIC test chain — {LABEL[slug]}",
                      published_at=GENERATED_AT[slug], published=paths.published_dir)
    out = CHAIN / "build" / slug
    if out.exists():
        shutil.rmtree(out)
    cmd = [sys.executable, "-m", "hc_valuation", "build", "--input", str(paths.workbook), "--policy", str(paths.policy),
           "--ledger-dir", str(LEDGER), "--out", str(out)] + (["--provider", provider] if provider else [])
    res = subprocess.run(cmd, capture_output=True, text=True, cwd=ROOT)
    if res.returncode != 0:
        raise SystemExit(f"build failed for {slug}:\n{res.stdout}\n{res.stderr}")
    print(f"published {rec['quarter']} as {rec['status']} (run {rec['run_id']}, booked {rec['booked_nav']:,.1f}); built into {out}")
    return out


